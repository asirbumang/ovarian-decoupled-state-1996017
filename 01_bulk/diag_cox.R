suppressMessages({library(data.table); library(survival)})
d <- fread("D:/子宫内膜异位症2/analysis/L0_bulk/results/survival_meta/scores_GSE26193.csv", data.table = FALSE)
cat("n:", nrow(d), " events:", sum(d$os_event == 1, na.rm = TRUE), "\n")
cat("os_days range:", range(d$os_days, na.rm = TRUE), "\n")
cat("decouple range:", range(d$decouple, na.rm = TRUE), " sd:", sd(d$decouple), "\n")
d$tier <- cut(d$decouple, quantile(d$decouple, c(0, .25, .75, 1), na.rm = TRUE), labels = c("Low", "Mid", "High"), include.lowest = TRUE)
cat("tier table:\n"); print(table(d$tier, useNA = "ifany"))
fx <- coxph(Surv(os_days, os_event) ~ as.numeric(tier), data = d)
print(summary(fx)$coefficients)
cat("n used:", fx$n, "\n")
